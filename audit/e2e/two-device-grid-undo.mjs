// DEF-011: Ctrl+Z inside a table after a pull must not wipe the other device's cells.
import { launch, BASE, sleep, ok, summary, resetMock, dump } from './lib.mjs'
await resetMock()
const A = await launch(), B = await launch()
const gridBox = p => p.evaluate(() => document.querySelector('[data-ds-grid-scroll]').getBoundingClientRect().toJSON())
async function typeCell(p, r, c, text) {
  const g = await gridBox(p)
  await p.mouse.click(g.x + 48 + 130 * c + 60, g.y + 26 + 24 * r + 12); await sleep(150)
  await p.keyboard.type(text); await p.keyboard.press('Enter'); await sleep(250)
}
const cells = p => p.evaluate(() => document.querySelector('[data-ds-grid-scroll]')?.innerText.split('\n').filter(Boolean) || [])
await A.page.goto(BASE + '/app', { waitUntil: 'networkidle' }); await sleep(600)
await A.page.getByRole('button', { name: /new project/i }).click(); await sleep(800)
await A.page.getByRole('button', { name: /^add$/i }).first().click(); await sleep(200)
await A.page.keyboard.type('Table Block'); await A.page.keyboard.press('Enter'); await sleep(800)
await typeCell(A.page, 0, 0, 'A-FIRST')
await sleep(3500)
await B.page.goto(BASE + '/app', { waitUntil: 'networkidle' }); await sleep(2500)
ok((await cells(B.page)).includes('A-FIRST'), 'B pulled the table')
await typeCell(A.page, 1, 0, 'A-SECOND')        // A's latest grid edit (top of A's grid undo)
await sleep(3500)
await B.page.evaluate(() => window.dispatchEvent(new Event('focus'))); await sleep(2500)
await typeCell(B.page, 5, 2, 'B-CELL')
await sleep(3500)
await A.page.evaluate(() => window.dispatchEvent(new Event('focus'))); await sleep(2500)
ok((await cells(A.page)).includes('B-CELL'), "A pulled B's cell", await cells(A.page))
// A: focus the grid and undo its own last edit
const g = await gridBox(A.page)
await A.page.mouse.click(g.x + 48 + 130 * 3 + 60, g.y + 26 + 24 * 3 + 12); await sleep(150)
await A.page.keyboard.press('Control+z'); await sleep(600)
const after = await cells(A.page)
ok(!after.includes('A-SECOND'), "A's own last cell edit is undone", after)
ok(after.includes('B-CELL'), "B's cell survives A's grid undo", after)
ok(after.includes('A-FIRST'), "and A's earlier cell is untouched", after)
await sleep(4000)
const docs = JSON.stringify((await dump()).tables.docs)
ok(docs.includes('B-CELL'), 'the server still has B\'s cell')
await A.browser.close(); await B.browser.close()
process.exit(summary())
